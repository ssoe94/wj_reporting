const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const checks=[], errors=[];
 const context=await browser.newContext({viewport:{width:1280,height:720}});
 // This context uses only loopback synthetic services; no connected WJ/MES session.
 await context.route('**/*',route=>{const u=new URL(route.request().url());return u.hostname==='127.0.0.1'?route.continue():route.abort();});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5198/production/plan?fixture_lang=ko');
 const workflow=page.locator('.plan-workflow');
 await workflow.getByRole('button',{name:'준비 검토',exact:true}).click();
 await workflow.getByText('MES 쓰기 OFF',{exact:true}).waitFor();
 await workflow.getByLabel('종료일',{exact:true}).fill('2026-10-10');
 await workflow.locator('tbody tr').filter({hasText:'2026-10-10'}).waitFor();
 assert.equal(await workflow.locator('tbody tr').count(),4);checks.push('Korean plan rows loaded from disposable Django API');
 assert.match(await workflow.locator('.plan-workflow__previews').innerText(),/2300.*|2300/);
 assert.match(await workflow.locator('.plan-workflow__previews').innerText(),/2026-10-11 08:00/);checks.push('2300-piece continuous campaign ends next-day 08:00');
 await workflow.evaluate(el=>el.scrollIntoView({block:'start'}));
 await page.screenshot({path:'output/plan-workflow/ko-preparation-1280x720.png'});
 const blocked=workflow.locator('.plan-workflow__preview').filter({hasText:'SYNTHETIC-UNCONFIRMED'});
 assert.equal(await blocked.getByRole('button',{name:'준비 저장'}).isDisabled(),true);checks.push('Unconfirmed material cannot prepare MES request');
 const first=workflow.locator('.plan-workflow__preview').filter({hasText:'SYNTHETIC-PART'}).first();
 if(await first.getByRole('button',{name:'준비 저장',exact:true}).isEnabled()) await first.getByRole('button',{name:'준비 저장',exact:true}).click();
 await workflow.locator('.plan-workflow__requests strong').waitFor();
 await workflow.locator('.plan-workflow__requests strong').waitFor();
 assert.equal(await workflow.locator('.plan-workflow__requests > div').count(),1);checks.push('One persistent disabled request saved without MES writes');
 await workflow.locator('.plan-workflow__previews').scrollIntoViewIfNeeded();
 await page.screenshot({path:'output/plan-workflow/ko-work-order-preview-1280x720.png'});
 await page.reload();await workflow.getByRole('button',{name:'준비 검토',exact:true}).click();
 await workflow.locator('.plan-workflow__requests strong').waitFor();
 assert.equal(await workflow.locator('.plan-workflow__requests > div').count(),1);checks.push('Request survives page reload');
 await workflow.locator('tbody tr').filter({hasText:'SYNTHETIC-PART'}).first().getByRole('button',{name:'확인',exact:true}).click();
 const editor=workflow.locator('form');
 await editor.getByLabel('확인 사유 / 근거',{exact:true}).fill('SYNTHETIC 화면 확인');
 await editor.getByLabel('현재 작업 버전과 입력한 원료·셋업 근거를 확인했습니다').check();
 await editor.evaluate(el=>el.scrollIntoView({block:'start'}));
 await page.screenshot({path:'output/plan-workflow/ko-material-editor-1280x720.png'});
 await editor.getByRole('button',{name:'이 버전 원료 확인',exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'output/plan-workflow/ko-material-action-1280x720.png'});
 assert.match(await editor.innerText(),/원료 소요량: 20/);checks.push('Exact material requirement and ID fields visible');
 // Inject a conflict response only in this disposable browser to verify draft recovery.
 await page.route('**/api/production/plan-workflow/',route=>route.request().method()==='POST'?route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({detail:'synthetic stale'})}):route.continue());
 await editor.getByRole('button',{name:'이 버전 원료 확인',exact:true}).click();
 await workflow.getByText('계획 또는 원료 원본이 변경되었습니다. 초안을 보존했습니다. 새 버전을 확인하세요.',{exact:true}).waitFor();
 assert.equal(await editor.getByLabel('확인 사유 / 근거',{exact:true}).inputValue(),'SYNTHETIC 화면 확인');checks.push('409 preserves editable material draft');
 await workflow.getByRole('status').scrollIntoViewIfNeeded();await page.screenshot({path:'output/plan-workflow/ko-stale-draft-1280x720.png'});
 await page.unroute('**/api/production/plan-workflow/');
 await editor.getByRole('button',{name:'이 버전 원료 확인',exact:true}).click();
 await workflow.getByText('로컬 준비를 저장했습니다. MES 쓰기는 OFF입니다.',{exact:true}).waitFor();
 assert.equal(await workflow.locator('form').count(),0);checks.push('Material approval saves successfully through real local Django API');
 await workflow.locator('tbody tr').filter({hasText:'SYNTHETIC-PART'}).first().getByRole('button',{name:'기본원료',exact:true}).click();
 const defaults=workflow.locator('form');
 assert.equal(await defaults.getByRole('button',{name:'새 기본 버전 저장',exact:true}).isDisabled(),true);
 await defaults.getByLabel('기본값 변경 근거',{exact:true}).fill('SYNTHETIC explicit reusable formula');
 await defaults.getByLabel('일회 대체가 아니라 이 품번의 기본원료 변경임을 확인합니다').check();
 await defaults.evaluate(el=>el.scrollIntoView({block:'start'}));
 await page.screenshot({path:'output/plan-workflow/ko-explicit-default-1280x720.png'});
 await defaults.getByRole('button',{name:'새 기본 버전 저장',exact:true}).click();
 await workflow.locator('form').waitFor({state:'detached'});checks.push('Default formula requires a separate explicit confirmation');
 const dimensions=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));assert.ok(dimensions.document<=dimensions.viewport);checks.push('No horizontal page overflow at 1280x720');
 const zh=await context.newPage();zh.on('pageerror',e=>errors.push(e.message));
 await zh.goto('http://127.0.0.1:5198/production/plan?fixture_lang=zh');
 const chinese=zh.locator('.plan-workflow');await chinese.getByRole('button',{name:'审核准备',exact:true}).click();
 await chinese.getByText('MES 写入关闭',{exact:true}).waitFor();await chinese.evaluate(el=>el.scrollIntoView({block:'start'}));
 await zh.screenshot({path:'output/plan-workflow/zh-preparation-1280x720.png'});checks.push('Chinese production-page rendering verified');
 await chinese.getByLabel('工艺',{exact:true}).selectOption('machining');
 await chinese.getByText('所选范围没有计划。',{exact:true}).waitFor();checks.push('Empty machining state verified');
 await zh.screenshot({path:'output/plan-workflow/zh-empty-1280x720.png'});
 await zh.route('**/api/production/plan-workflow/**',route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"SYNTHETIC unavailable"}'}));
 await chinese.getByRole('button',{name:'刷新',exact:true}).click();
 await chinese.getByText('准备信息加载失败，现有生产计划仍可使用。',{exact:true}).waitFor();
 await zh.screenshot({path:'output/plan-workflow/zh-error-1280x720.png'});checks.push('Workflow failure leaves existing plan page usable');
 assert.deepEqual(errors,[]);checks.push('No browser runtime errors');
 fs.writeFileSync('output/plan-workflow/browser-checks.json',JSON.stringify({fixture_only:true,viewport:'1280x720',checks,errors},null,2));
 console.log(checks.join('\n'));await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
